from pathlib import Path
import uuid

import nibabel as nib
import numpy as np
import nrrd

from .schema import LABELS

FORMAT = 'slicer-seg-v1'
FILENAME = 'aaoca_11.seg.nrrd'
COLORS = ((230, 80, 80), (80, 140, 240), (250, 150, 80), (110, 100, 230),
          (190, 100, 150), (255, 190, 50), (60, 200, 180), (170, 100, 220),
          (90, 160, 240), (70, 110, 210), (255, 240, 70))


def export_segmentation(image_path, mask_root, destination):
    source = nib.load(str(image_path))
    root, destination = Path(mask_root), Path(destination)
    if source.ndim != 3 or source.header.get_xyzt_units()[0] != 'mm':
        raise ValueError('标签导出需要三维毫米单位 CT')
    layers, segments, statistics = [], [], {}
    for index, (label, name, chinese, task) in enumerate(LABELS):
        mask = nib.load(str(root / task / f'{name}.nii.gz'))
        if (mask.shape != source.shape or mask.header.get_xyzt_units()[0] != 'mm'
                or not np.allclose(mask.affine, source.affine, atol=1e-3, rtol=0)):
            raise ValueError(f'{name}: 掩膜与原始 CT 的空间网格不同')
        data = np.asanyarray(mask.dataobj)
        if not np.isin(data, [0, 1]).all():
            raise ValueError(f'{name}: 掩膜须为二值')
        selected = data == 1
        layer_index = next((i for i, layer in enumerate(layers) if not np.any(layer[selected])), len(layers))
        if layer_index == len(layers):
            layers.append(np.zeros(source.shape, dtype=np.uint8))
        layers[layer_index][selected] = label
        segments.append((label, name, layer_index, COLORS[index]))
        count = int(np.count_nonzero(selected))
        statistics[name] = {'id': label, 'name_zh': chinese, 'voxels': count,
                            'volume_mm3': count * abs(float(np.linalg.det(source.affine[:3, :3])))}
    # 独立结构仅在互不重叠时共用一层，保留全部原始预测。
    voxels = layers[0] if len(layers) == 1 else np.stack(layers, axis=0)
    directions = source.affine[:3, :3].T
    header = {'space': 'right-anterior-superior', 'space origin': source.affine[:3, 3],
              'space directions': directions if voxels.ndim == 3 else np.vstack((np.full(3, np.nan), directions)),
              'kinds': ['domain'] * 3 if voxels.ndim == 3 else ['list', 'domain', 'domain', 'domain'],
              'encoding': 'gzip', 'Segmentation_SourceRepresentation': 'Binary labelmap',
              'Segmentation_ContainedRepresentationNames': 'Binary labelmap|',
              'Segmentation_ReferenceImageExtentOffset': '0 0 0'}
    for index, (label, name, layer_index, color) in enumerate(segments):
        prefix = f'Segment{index}_'
        header.update({prefix + 'ID': f'label_{label:02d}', prefix + 'Name': name,
                       prefix + 'Color': ' '.join(str(v / 255) for v in color),
                       prefix + 'Layer': str(layer_index), prefix + 'LabelValue': str(label),
                       prefix + 'NameAutoGenerated': '0', prefix + 'ColorAutoGenerated': '0'})
    destination.mkdir(parents=True, exist_ok=True)
    final = destination / FILENAME
    temporary = destination / ('.' + uuid.uuid4().hex + '.seg.nrrd')
    try:
        nrrd.write(str(temporary), voxels, header=header, compression_level=1, index_order='F')
        restored, metadata = nrrd.read(str(temporary), index_order='F')
        if (not np.array_equal(voxels, restored)
                or not np.allclose(metadata['space origin'], source.affine[:3, 3], atol=1e-6)
                or not np.allclose(metadata['space directions'][-3:], directions, atol=1e-6)
                or any(metadata[f'Segment{i}_Name'] != name for i, (_, name, _, _) in enumerate(segments))):
            raise ValueError('医生编辑标签的完整回读核验失败')
        temporary.replace(final)
    finally:
        temporary.unlink(missing_ok=True)
    return final, {'review_required': True, 'classes': statistics, 'layers': len(layers),
                   'empty_masks': [name for name, row in statistics.items() if not row['voxels']],
                   'overlaps_preserved': True, 'original_grid': True, 'all_voxels_roundtrip_equal': True}
